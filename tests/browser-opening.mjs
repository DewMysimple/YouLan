  const samples=await b.screenshot(null,points);
  assert.deepEqual(samples[0],samples[1]);assert.deepEqual(samples[0],samples[2]);
  assert.ok(samples[0][0]>220,'paper texture tiles at native512px with no 3D content');
  // Existing scenes and camera state survive the insertion and return trip.
  await b.set(['场景选择'],'当前场景','场景2·标本纵深');await b.delay(180);
  assert.deepEqual(await b.evaluate('__camera.position.toArray()'),original);
  assert.equal(await b.evaluate('document.querySelector(".viewer-opening").hidden'),true);
  assert.equal(await b.evaluate(`getComputedStyle(document.querySelector('.viewer > canvas')).visibility`),'visible');
  await b.set(['场景选择'],'当前场景','场景12·字符物理实验');await b.delay(180);
  assert.ok(await b.evaluate(`__observed.findLast(o=>o.name==='场景12·字符物理实验').userData.character.ready`));
  await b.set(['场景选择'],'当前场景','场景1·纸纹序章');assert.equal(await stage(),'paper');
  await b.click(panel,'重播开场');await b.delay(200);
  await b.evaluate(`Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));`);
  const hiddenStage=await stage();await b.delay(1700);assert.equal(await stage(),hiddenStage);
  await b.evaluate(`delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));`);
  await b.until(`document.querySelector('.viewer-opening').dataset.stage==='ready'`);
  // Accessible native button activation and reduced-motion immediate entry.
  await b.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
  await b.evaluate(`document.querySelector('.opening-enter').focus()`);
  await b.send('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13,nativeVirtualKeyCode:13,text:'\r'});
