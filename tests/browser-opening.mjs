  await b.screenshot('05-paper-only.png');
  assert.equal(await b.evaluate(`getComputedStyle(document.querySelector('.opening-enter img')).opacity`),'0');
  assert.equal(await b.evaluate(`document.querySelectorAll('.viewer-opening canvas,.viewer-opening iframe').length`),0);
  assert.equal(await b.evaluate(`getComputedStyle(document.querySelector('.viewer > canvas')).visibility`),'hidden');
